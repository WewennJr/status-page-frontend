export function t(lang: Lang, key: string): string {
  return messages[lang]?.[key] ?? messages.fr[key] ?? key
}

export function normalizeLang(value: string | null | undefined): Lang | null {
  if (value === "fr" || value === "en") return value
  return null
}

export function detectLang(defaultLang: string): Lang {
  const stored = normalizeLang(localStorage.getItem("sp-lang"))
  if (stored) return stored
  const fromSettings = normalizeLang(defaultLang)
  if (fromSettings) return fromSettings
  const browser = navigator.language.toLowerCase()
  if (browser.startsWith("fr")) return "fr"
  return "en"
}
